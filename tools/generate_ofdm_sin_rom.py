#!/usr/bin/env python3
"""Write rtl/ofdm_sin_rom.v: a quarter-wave sine table for ofdm_frame_conditioner's NCO (issue #48).

257 entries, round(32767 * sin(2*pi*k/1024)) for k = 0..256, so that sin(0) = 0 and sin(pi/2) =
32767 exactly and a zero phase leaves a sample unchanged up to the Q1.15 scale. The module gives
sin and cos of a 10-bit phase (1024 steps per turn) by quadrant symmetry.

    python tools/generate_ofdm_sin_rom.py
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "blocks/block_08_modulation_and_synchronization/rtl/ofdm_sin_rom.v"


def table() -> list[int]:
    return [round(32767 * math.sin(2 * math.pi * k / 1024)) for k in range(257)]


def verilog() -> str:
    lines = [
        "`timescale 1ns/1ps",
        "",
        "// GENERATED by tools/generate_ofdm_sin_rom.py, do not edit.",
        "// sin and cos of phase * 2*pi/1024, Q1.15 (32767 = 1), from a quarter-wave table of 257 entries.",
        "// A function and continuous assignments (see ofdm_sync_preamble_rom for why not always @(*)).",
        "module ofdm_sin_rom (",
        "    input  wire [9:0]         phase,",
        "    output wire signed [15:0] sin_out,",
        "    output wire signed [15:0] cos_out",
        ");",
        "function [15:0] quarter(input [8:0] k);     // round(32767 * sin(2*pi*k/1024)), k = 0..256",
        "    begin",
        "        case (k)",
    ]
    for k, v in enumerate(table()):
        lines.append(f"        9'd{k}: quarter = 16'd{v};")
    lines += [
        "        default: quarter = 16'd0;",
        "        endcase",
        "    end",
        "endfunction",
        "function [15:0] sine(input [9:0] p);",
        "    begin",
        "        case (p[9:8])",
        "        2'd0: sine = quarter({1'b0, p[7:0]});",
        "        2'd1: sine = quarter(9'd256 - {1'b0, p[7:0]});",
        "        2'd2: sine = -quarter({1'b0, p[7:0]});",
        "        default: sine = -quarter(9'd256 - {1'b0, p[7:0]});",
        "        endcase",
        "    end",
        "endfunction",
        "assign sin_out = sine(phase);",
        "assign cos_out = sine(phase + 10'd256);",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(verilog(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
