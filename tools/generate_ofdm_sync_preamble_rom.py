#!/usr/bin/env python3
"""Write rtl/ofdm_sync_preamble_rom.v: the Schmidl & Cox preamble of tools/ofdm_rf_link.py as a ROM.

ofdm_radio_core sends this preamble (CP 16 + a 64-sample body of two equal halves) in front of the
modem's training and data symbols, at the level of the modem's own output, so the frame on the air
is the frame of stage 4a. The level is RMS = 3680 (-19 dBFS), the RTL transmitter's: the script
checks that against one frame of the RTL transmitter (needs iverilog) unless --no-check.

    python tools/generate_ofdm_sync_preamble_rom.py
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import ofdm_rf_link as O  # noqa: E402

OUT = ROOT / "blocks/block_08_modulation_and_synchronization/rtl/ofdm_sync_preamble_rom.v"
RMS = 3680.0


def rom_values() -> np.ndarray:
    pre = np.round(O.preamble(RMS))
    assert np.all(np.abs(pre.real) < 32768) and np.all(np.abs(pre.imag) < 32768)
    return pre


def verilog(pre: np.ndarray) -> str:
    lines = [
        "`timescale 1ns/1ps",
        "",
        "// GENERATED by tools/generate_ofdm_sync_preamble_rom.py, do not edit.",
        "// Schmidl & Cox preamble of tools/ofdm_rf_link.py (seed 7): CP 16 + 64 samples whose two",
        f"// 32-sample halves are equal, Q1.15, RMS {RMS:.0f} (-19 dBFS, the level of the modem's TX output).",
        "// A function and continuous assignments, not always @(*): a simulator runs always @(*) only",
        "// when the index changes, so index 0 held from time 0 would read X.",
        "module ofdm_sync_preamble_rom (",
        "    input  wire [6:0]         index,      // 0..79",
        "    output wire signed [15:0] re,",
        "    output wire signed [15:0] im",
        ");",
        "function [31:0] sample(input [6:0] k);     // {im, re}",
        "    begin",
        "        case (k)",
    ]
    for k, v in enumerate(pre):
        r, i = int(v.real), int(v.imag)
        lines.append(f"        7'd{k}: sample = {{16'h{i & 0xFFFF:04X}, 16'h{r & 0xFFFF:04X}}};   // {r} {i}")
    lines += ["        default: sample = 32'd0;", "        endcase", "    end", "endfunction",
              "wire [31:0] word = sample(index);", "assign re = word[15:0];", "assign im = word[31:16];",
              "endmodule", ""]
    return "\n".join(lines)


def check_level() -> float:
    rng = np.random.default_rng(1)
    groups, _ = O.frame_bits(8, 1, rng)
    with tempfile.TemporaryDirectory() as tmp:
        tx = O.rtl_tx(Path(tmp), groups, 1)
    return float(np.sqrt(np.mean(np.abs(tx) ** 2)))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--no-check", action="store_true", help="skip the RTL transmitter level check")
    args = ap.parse_args()
    if not args.no_check:
        level = check_level()
        print(f"RTL transmitter RMS {level:.0f} (preamble {RMS:.0f})")
        assert abs(level / RMS - 1) < 0.1, level
    OUT.write_text(verilog(rom_values()), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
