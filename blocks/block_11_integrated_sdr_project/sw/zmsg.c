#define FRAME_SYMS 152
#define PRE_BITS 48
#define PKT_BYTES 32
#define PKT_BITS 256
#define SPS 8
#define N_FRAMES 28
#define FS 3840000
#define GP_BASE 0x79040000u
#define MODE 0x2D630u           /* Lab 11.45: QPSK, raw ADC, DC blocker, Costas, Gardner, diff */
#define BITS_READ 0x10000u      /* gp_ctrl[16]: decoded-bit readout */
#define LISTEN 0x40000u         /* gp_ctrl[18]: listen mode (issue #68) */
#define ONCE_PAD_HEAD 8         /* silent symbols before the lead-in */
#define ONCE_PAD_TAIL 256       /* silent symbols after the frame: the RRC tail, then zeros held */
#define ONCE_FLUSH 16           /* extra zero buffers so the close does not cut the message (see cmd_send_once) */

static char phy[128];

static uint16_t crc16(const uint8_t *d, int n)
{
    uint16_t c = 0xFFFF;
    for (int i = 0; i < n; i++) {
        c ^= (uint16_t)(d[i] << 8);
        for (int b = 0; b < 8; b++)
            c = (c & 0x8000) ? (uint16_t)((c << 1) ^ 0x1021) : (uint16_t)(c << 1);
    }
    return c;
}

static void pn9(uint8_t *w, int n)
{
    unsigned s = 0x1FF;
    for (int i = 0; i < n; i++) {
        w[i] = s & 1;
        s = ((s << 1) | (((s >> 8) ^ (s >> 4)) & 1)) & 0x1FF;
    }
}

static int find_phy(void)
{
    char p[256], name[64];
    for (int i = 0; i < 8; i++) {
        snprintf(p, sizeof p, "/sys/bus/iio/devices/iio:device%d/name", i);
        FILE *f = fopen(p, "r");
        if (!f)
            continue;
        if (fgets(name, sizeof name, f) && strncmp(name, "ad9361-phy", 10) == 0) {
            snprintf(phy, sizeof phy, "/sys/bus/iio/devices/iio:device%d", i);
            fclose(f);
            return 0;
        }
        fclose(f);
    }
    return -1;
}

static void attr(const char *name, const char *value)
{
    char p[256];
    snprintf(p, sizeof p, "%s/%s", phy, name);
    FILE *f = fopen(p, "w");
    if (!f) {
        fprintf(stderr, "cannot write %s\n", p);
        return;
    }
    fputs(value, f);
    fclose(f);
}

static int writer_running(void);

static void signal_writers(int sig)
{
    DIR *d = opendir("/proc");
    struct dirent *e;
    char p[300], comm[64];
    while (d && (e = readdir(d))) {
        int pid = atoi(e->d_name);
        if (pid <= 0)
            continue;
        snprintf(p, sizeof p, "/proc/%d/comm", pid);
        FILE *f = fopen(p, "r");
        if (!f)
            continue;
        if (fgets(comm, sizeof comm, f) && strncmp(comm, "iio_writedev", 12) == 0)
            kill(pid, sig);
        fclose(f);
    }
    if (d)
        closedir(d);
}

/* Stop running transmitters with SIGTERM first: iio_writedev then closes its buffer and the DMA
 * stops. After SIGKILL the DAC kept playing the old cyclic buffer on board A; it was silent only
 * while the TX LO was off, and the next `send --once` put about 100 ms of the old message on the
 * air before its own buffer took over. SIGKILL only if a writer ignores SIGTERM for a second. */
static void kill_writers(void)
{
    signal_writers(SIGTERM);
    for (int i = 0; i < 10 && writer_running(); i++)
        usleep(100000);
    if (writer_running())
        signal_writers(SIGKILL);
    usleep(300000);
}

static int writer_running(void)
{
    DIR *d = opendir("/proc");
    struct dirent *e;
    char p[300], comm[64];
    int n = 0;
    while (d && (e = readdir(d))) {
        int pid = atoi(e->d_name);
        if (pid <= 0)
            continue;
        snprintf(p, sizeof p, "/proc/%d/comm", pid);
        FILE *f = fopen(p, "r");
        if (!f)
            continue;
        if (fgets(comm, sizeof comm, f) && strncmp(comm, "iio_writedev", 12) == 0)
            n++;
        fclose(f);
    }
    if (d)
        closedir(d);
    return n;
}

/* Phase state p (0..3) -> QPSK symbol, as qpsk_diff_encoder.v + qpsk_symbol_mapper.v. */
static void state_symbol(int p, double *si, double *sq)
{
    int p1 = (p >> 1) & 1, p0 = p & 1;
    int e0 = p0 ^ p1, e1 = p1;
    *si = (1.0 - 2.0 * e0) / sqrt(2.0);
    *sq = (1.0 - 2.0 * e1) / sqrt(2.0);
}

/* packet-v1 -> the 304 frame bits (preamble + possibly whitened packet). */
static int frame_bits(const char *text, int seq, int whiten, uint8_t *bits)
{
    uint8_t pkt[PKT_BYTES] = {0}, w[PKT_BITS];
    int len = (int)strlen(text);
    if (len > 27) {
        fprintf(stderr, "payload is %d bytes; packet-v1 limit is 27\n", len);
        return -1;
    }
    pkt[0] = (uint8_t)len;
    pkt[1] = (uint8_t)(seq & 0xFF);
    pkt[2] = (uint8_t)((seq >> 8) & 0xFF);
    memcpy(pkt + 3, text, len);
    uint16_t c = crc16(pkt, 30);
    pkt[30] = (uint8_t)(c & 0xFF);
    pkt[31] = (uint8_t)(c >> 8);

    pn9(w, PKT_BITS);
    for (int i = 0; i < PRE_BITS; i++)
        bits[i] = PREAMBLE[i];
    for (int i = 0; i < PKT_BITS; i++) {
        uint8_t b = (pkt[i / 8] >> (i % 8)) & 1;
        bits[PRE_BITS + i] = whiten ? (uint8_t)(b ^ w[i]) : b;
    }
    return len;
}

/* Write an attribute only if its current numeric value differs. Rewriting the TX settings
 * retunes the chip even when nothing changes, and on the bench that put a short click, three
 * times stronger than the message, on the air about 65 ms before every one-shot message; a
 * listening receiver takes it for a packet. */
static void attr_num(const char *name, double value, double tol)
{
    char p[256], buf[64];
    snprintf(p, sizeof p, "%s/%s", phy, name);
    FILE *f = fopen(p, "r");
    if (f) {
        int same = fgets(buf, sizeof buf, f) && fabs(atof(buf) - value) <= tol;
        fclose(f);
        if (same)
            return;
    }
    snprintf(buf, sizeof buf, "%.2f", value);
    attr(name, buf);
}

static int start_tx(double tx_gain, long lo)
{
    kill_writers();
    attr_num("out_voltage_sampling_frequency", FS, 0.5);
    attr_num("out_altvoltage1_TX_LO_frequency", (double)lo, 0.5);
    attr_num("out_voltage0_hardwaregain", tx_gain, 0.01);
    attr_num("out_altvoltage1_TX_LO_powerdown", 0, 0.1);
    return 0;
}

static int write_iq(const int16_t *iq, int n)
{
    FILE *f = fopen("/tmp/zmsg.bin", "wb");
    if (!f || fwrite(iq, sizeof(int16_t), 2 * n, f) != (size_t)(2 * n)) {
        perror("/tmp/zmsg.bin");
        return -1;
    }
    fclose(f);
    return 0;
}

/* One message, sent once: silence, lead-in, reference, frame, silence; linear RRC. */
static int cmd_send_once(const char *text, int seq, double tx_gain, long lo, int whiten, int lead)
{
    uint8_t bits[PRE_BITS + PKT_BITS];
    int len = frame_bits(text, seq, whiten, bits);
    if (len < 0)
        return 2;
    int nsym = ONCE_PAD_HEAD + lead + 1 + FRAME_SYMS + ONCE_PAD_TAIL, n = nsym * SPS;
    double *si = calloc(nsym, sizeof(double)), *sq = calloc(nsym, sizeof(double));
    double *yi = calloc(n, sizeof(double)), *yq = calloc(n, sizeof(double));
    int16_t *iq = malloc(2 * n * sizeof(int16_t));
    if (!si || !sq || !yi || !yq || !iq)
        return 2;
    int k = ONCE_PAD_HEAD;
    for (int j = 0; j < lead; j++, k++)            /* ..., 0, 2, 0, 2: ends in state 2 */
        state_symbol(((lead - j) % 2) ? 2 : 0, &si[k], &sq[k]);
    state_symbol(0, &si[k], &sq[k]);               /* reference: the encoder's starting state */
    k++;
    int p = 0;
    for (int j = 0; j < FRAME_SYMS; j++, k++) {
        int d0 = bits[2 * j], d1 = bits[2 * j + 1];
        p = (p + ((d1 << 1) | (d0 ^ d1))) & 3;
        state_symbol(p, &si[k], &sq[k]);
    }
    for (int m = 0; m < n; m++) {
        double ai = 0, aq = 0;
        for (int t = 0; t < RRC_TAPS_N; t++) {
            int j = m - t;
            if (j < 0 || j % SPS)
                continue;
            ai += RRC_TAPS[t] * si[j / SPS];
            aq += RRC_TAPS[t] * sq[j / SPS];
        }
        yi[m] = ai;
        yq[m] = aq;
    }
    double peak = 0;
    for (int m = 0; m < n; m++) {
        double a = sqrt(yi[m] * yi[m] + yq[m] * yq[m]);
        if (a > peak)
            peak = a;
    }
    double g = 0.70 * 32767 / peak;
    for (int m = 0; m < n; m++) {
        iq[2 * m] = (int16_t)lround(yi[m] * g);
        iq[2 * m + 1] = (int16_t)lround(yq[m] * g);
    }
    if (write_iq(iq, n))
        return 2;
    if (getenv("ZMSG_DRY_RUN")) {
        printf("dry run: wrote /tmp/zmsg.bin (%d samples, one shot)\n", n);
        return 0;
    }
    /* A plain iio_writedev queues the buffer and closes it at once, and closing stops the DMA:
     * on the bench only the first ~1000 samples went out. The file therefore carries ONCE_FLUSH
     * more buffers of zeros. The kernel has 4 blocks, so queueing the 5th waits until the first
     * (the message) has gone out; with 5 buffers 1 frame in 4 was still cut on the bench, so 16. */
    FILE *fz = fopen("/tmp/zmsg.bin", "ab");
    int16_t zero[2 * SPS] = {0};
    for (int m = 0; fz && m < ONCE_FLUSH * n / SPS; m++)
        fwrite(zero, sizeof zero, 1, fz);
    if (fz)
        fclose(fz);
    start_tx(tx_gain, lo);
    char c2[256];
    snprintf(c2, sizeof c2, "iio_writedev -b %d -s %d cf-ad9361-dds-core-lpc voltage0 voltage1 "
                            "< /tmp/zmsg.bin > /tmp/zmsg.log 2>&1", n, (ONCE_FLUSH + 1) * n);
    if (system(c2) != 0) {
        fprintf(stderr, "iio_writedev failed, see /tmp/zmsg.log\n");
        return 1;
    }
    printf("TX once sequence=%d bytes=%d payload=\"%s\" lead=%d%s\n", seq, len, text, lead,
           whiten ? "" : " (not whitened)");
    return 0;
}

static int cmd_send(const char *text, int seq, double tx_gain, long lo, int whiten)
{
    uint8_t bits[PRE_BITS + PKT_BITS];
    int len = frame_bits(text, seq, whiten, bits);
    if (len < 0)
        return 2;

    /* Differential encoding over the whole cyclic buffer (matches qpsk_diff_encoder.v). */
    int nsym = N_FRAMES * FRAME_SYMS, n = nsym * SPS;
    double *si = calloc(nsym, sizeof(double)), *sq = calloc(nsym, sizeof(double));
    double *yi = calloc(n, sizeof(double)), *yq = calloc(n, sizeof(double));
    int16_t *iq = malloc(2 * n * sizeof(int16_t));
    if (!si || !sq || !yi || !yq || !iq)
        return 2;
    int p = 0;
    for (int k = 0; k < nsym; k++) {
        int d0 = bits[(2 * k) % (PRE_BITS + PKT_BITS)], d1 = bits[(2 * k + 1) % (PRE_BITS + PKT_BITS)];
        p = (p + ((d1 << 1) | (d0 ^ d1))) & 3;
        int p1 = (p >> 1) & 1, p0 = p & 1;
        int e0 = p0 ^ p1, e1 = p1;
        si[k] = (1.0 - 2.0 * e0) / sqrt(2.0);
        sq[k] = (1.0 - 2.0 * e1) / sqrt(2.0);
    }
    /* Circular RRC: the upsampled stream has one nonzero sample per symbol at index 8k. */
    for (int m = 0; m < n; m++) {
        double ai = 0, aq = 0;
        for (int t = 0; t < RRC_TAPS_N; t++) {
            int j = m - t;
            if (j < 0)
                j += n;
            if (j % SPS)
                continue;
            ai += RRC_TAPS[t] * si[j / SPS];
            aq += RRC_TAPS[t] * sq[j / SPS];
        }
        yi[m] = ai;
        yq[m] = aq;
    }
    double peak = 0;
    for (int m = 0; m < n; m++) {
        double a = sqrt(yi[m] * yi[m] + yq[m] * yq[m]);
        if (a > peak)
            peak = a;
    }
    double g = 0.70 * 32767 / peak;
    for (int m = 0; m < n; m++) {
        iq[2 * m] = (int16_t)lround(yi[m] * g);
        iq[2 * m + 1] = (int16_t)lround(yq[m] * g);
    }
    if (write_iq(iq, n))
        return 2;
    if (getenv("ZMSG_DRY_RUN")) {
        printf("dry run: wrote /tmp/zmsg.bin (%d samples)\n", n);
        return 0;
    }

    start_tx(tx_gain, lo);
    for (int tries = 0; tries < 2; tries++) {
        char c2[256];
        snprintf(c2, sizeof c2, "nohup iio_writedev -c -b %d -s %d cf-ad9361-dds-core-lpc voltage0 voltage1 "
                                "< /tmp/zmsg.bin > /tmp/zmsg.log 2>&1 &", n, n);
        if (system(c2) != 0)
            fprintf(stderr, "could not start iio_writedev\n");
        sleep(1);
        if (writer_running())
            break;
        /* A stuck DAC buffer: rebind the DDS driver once and retry. */
        system("d=$(ls /sys/bus/platform/drivers/cf_axi_dds/ | grep dds-core | head -1); "
               "[ -n \"$d\" ] && echo $d > /sys/bus/platform/drivers/cf_axi_dds/unbind && sleep 1 && "
               "echo $d > /sys/bus/platform/drivers/cf_axi_dds/bind; sleep 2");
    }
    if (!writer_running()) {
        fprintf(stderr, "transmitter did not start, see /tmp/zmsg.log\n");
        return 1;
    }
    printf("TX sequence=%d bytes=%d payload=\"%s\"%s\n", seq, len, text, whiten ? "" : " (not whitened)");
    return 0;
}

static int cmd_stop(void)
{
    kill_writers();
    /* A writer killed with SIGKILL earlier (by another tool) leaves its cyclic buffer playing.
     * Replace it with a cyclic buffer of zeros and stop that one properly, so the DMA is idle. */
    if (getenv("ZMSG_NO_DRAIN") == NULL) {
        int16_t zero[2 * 1024] = {0};
        FILE *f = fopen("/tmp/zmsg_zero.bin", "wb");
        if (f) {
            fwrite(zero, sizeof zero, 1, f);
            fclose(f);
            if (system("nohup iio_writedev -c -b 1024 -s 1024 cf-ad9361-dds-core-lpc voltage0 voltage1 "
                       "< /tmp/zmsg_zero.bin > /dev/null 2>&1 &") == 0) {
                usleep(500000);
                kill_writers();
            }
        }
    }
    attr("out_voltage0_hardwaregain", "-89.75");
    attr("out_altvoltage1_TX_LO_powerdown", "1");
    printf("transmitter stopped\n");
    return 0;
}

static volatile uint32_t *gp;
static volatile sig_atomic_t stop_requested;
static void on_term(int sig) { (void)sig; stop_requested = 1; }
static void wr(uint32_t off, uint32_t v) { gp[(0x400 + off) / 4] = v; }
static uint32_t rd(uint32_t off) { return gp[(0x400 + off) / 4]; }
#define R_CTRL 0x04
#define R_STAT 0x08
#define R_FRAME 0x44
#define R_RECV 0x48
#define R_PRE 0x84
#define R_OFF 0xC4
#define R_CAP 0x1C8

static double now_s(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return ts.tv_sec + ts.tv_nsec * 1e-9;
}

static int cmd_receive(int count, int attempts, int rx_gain, long lo, int whiten, int quiet, int listen,
                       double timeout)
{
    char v[64];
    snprintf(v, sizeof v, "%d", FS);
    attr("in_voltage_sampling_frequency", v);
    snprintf(v, sizeof v, "%ld", lo);
    attr("out_altvoltage0_RX_LO_frequency", v);
    attr("in_voltage0_gain_control_mode", "manual");
    snprintf(v, sizeof v, "%d", rx_gain);
    attr("in_voltage0_hardwaregain", v);

    int fd = open("/dev/mem", O_RDWR | O_SYNC);
    if (fd < 0) {
        perror("/dev/mem");
        return 2;
    }
    gp = mmap(NULL, 0x1000, PROT_READ | PROT_WRITE, MAP_SHARED, fd, GP_BASE);
    if (gp == MAP_FAILED) {
        perror("mmap");
        return 2;
    }
    if (gp[0x508 / 4] != 0x4250534Bu) {
        fprintf(stderr, "no course modem at 0x%08x (signature 0x%08x)\n", GP_BASE, gp[0x508 / 4]);
        return 2;
    }
    uint8_t w[PKT_BITS];
    pn9(w, PKT_BITS);
    uint32_t mode = MODE | (listen ? LISTEN : 0);
    int locked = 0, good = 0, bad = 0, timeouts = 0, k;
    double t_end = now_s() + timeout;
    signal(SIGTERM, on_term);   /* a plain kill ends the loop and still prints the summary */
    signal(SIGINT, on_term);
    for (k = 0; !stop_requested && good < count && (listen ? now_s() < t_end : k < attempts); k++) {
        wr(R_FRAME, FRAME_SYMS);
        wr(R_PRE, PRE_BITS);
        wr(R_OFF, (uint32_t)(k % 8));
        /* Hold start (and clear, below) for a while: the bridge samples gp_ctrl in the modem's
         * clock domain through a two-flop synchronizer, and a pulse made of two back-to-back
         * mmap writes is shorter than its clock. On the bench about one start in seven was lost
         * that way (status 0x810: idle, neither done nor timeout); devmem is slow enough never
         * to hit it. */
        wr(R_CTRL, mode);
        wr(R_CTRL, mode | 1);
        usleep(20);
        wr(R_CTRL, mode);
        uint32_t s = 0;
        double t_poll = now_s() + (listen ? 0.5 : 0.2);   /* the listen window is 136 ms */
        while (now_s() < t_poll) {
            s = rd(R_STAT);
            if (s & 0xC)
                break;
        }
        if (s & 0x8)
            timeouts++;
        /* The counter reports done at the end of the frame, but the sampler keeps emitting the
         * RX_SAMPLE_MARGIN (256) symbols after it, about 0.5 ms, and those still shift through the
         * decoded-bit register. Read it only after they are out (the Python tool never noticed:
         * one devmem call takes milliseconds). Only after a frame: when listening, a wait after
         * every timeout would leave the receiver deaf for 5 ms of every ~140 ms attempt. */
        if (s & 0x4)
            usleep(5000);
        uint32_t recv = rd(R_RECV);
        if (getenv("ZMSG_DEBUG"))
            fprintf(stderr, "%.4f attempt %d status 0x%03x recv %u\n", now_s(), k, s, recv);
        wr(R_CTRL, mode | 2);
        usleep(20);
        wr(R_CTRL, mode);
        /* The received-symbol count keeps its value from an earlier attempt until the next
         * frame completes; only the done bit says that this attempt locked. */
        if (!(s & 0x4) || recv != FRAME_SYMS)
            continue;
        locked++;
        uint32_t words[10];
        wr(R_CTRL, mode | BITS_READ);
        for (int a = 0; a < 10; a++) {
            wr(R_OFF, (uint32_t)a);
            words[a] = rd(R_CAP);
        }
        wr(R_CTRL, mode);
        uint8_t pkt[PKT_BYTES] = {0};
        for (int i = PRE_BITS; i < 2 * FRAME_SYMS; i++) {
            int pos = 2 * (FRAME_SYMS - 1 - i / 2) + (i % 2);
            int b = (words[pos / 32] >> (pos % 32)) & 1;
            int j = i - PRE_BITS;
            if (whiten)
                b ^= w[j];
            pkt[j / 8] |= (uint8_t)(b << (j % 8));
        }
        uint16_t c = crc16(pkt, 30);
        int crc_ok = (pkt[30] | (pkt[31] << 8)) == c;
        int len = pkt[0];
        int seq = pkt[1] | (pkt[2] << 8);
        if (crc_ok && len <= 27) {
            good++;
            printf("RX sequence=%d bytes=%d crc=OK payload=\"%.*s\"\n", seq, len, len, (char *)pkt + 3);
            fflush(stdout);
        } else {
            bad++;
            if (!quiet)
                printf("RX frame locked, crc=BAD\n");
            if (getenv("ZMSG_DEBUG")) {
                fprintf(stderr, "bad packet");
                for (int i = 0; i < PKT_BYTES; i++)
                    fprintf(stderr, " %02x", pkt[i]);
                fprintf(stderr, "\n");
            }
        }
    }
    gp[(0x400 + R_CTRL) / 4] = 0;
    fprintf(stderr, "receptions %d, locked %d, delivered %d, crc failures %d, timeouts %d\n", k, locked, good, bad,
            timeouts);
    return good ? 0 : 1;
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr, "usage: zmsg send <text> [--seq N] [--tx-gain dB] [--lo Hz] [--no-whiten] [--once [--lead N]]\n"
                        "       zmsg stop\n"
                        "       zmsg receive [--count N] [--attempts N] [--rx-gain dB] [--lo Hz] [--no-whiten] [--quiet]\n"
                        "                    [--listen [--timeout s]]\n");
        return 2;
    }
    /* ZMSG_DRY_RUN: build /tmp/zmsg.bin and stop, without a board (tests/test_zmsg_once.py). */
    if (!getenv("ZMSG_DRY_RUN") && find_phy()) {
        fprintf(stderr, "ad9361-phy not found\n");
        return 2;
    }
    int seq = 0, whiten = 1, count = 1, attempts = 32, rx_gain = 50, quiet = 0, once = 0, lead = 64, listen = 0;
    double timeout = 10.0;
    double tx_gain = -10.0;
    long lo = 915000000L;
    for (int i = 2; i < argc; i++) {
        if (!strcmp(argv[i], "--seq") && i + 1 < argc) seq = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--tx-gain") && i + 1 < argc) tx_gain = atof(argv[++i]);
        else if (!strcmp(argv[i], "--rx-gain") && i + 1 < argc) rx_gain = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--lo") && i + 1 < argc) lo = atol(argv[++i]);
        else if (!strcmp(argv[i], "--count") && i + 1 < argc) count = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--attempts") && i + 1 < argc) attempts = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--no-whiten")) whiten = 0;
        else if (!strcmp(argv[i], "--quiet")) quiet = 1;
        else if (!strcmp(argv[i], "--once")) once = 1;
        else if (!strcmp(argv[i], "--lead") && i + 1 < argc) lead = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--listen")) listen = 1;
        else if (!strcmp(argv[i], "--timeout") && i + 1 < argc) timeout = atof(argv[++i]);
    }
    if (lead < 0 || lead > 1024) {
        fprintf(stderr, "--lead must be 0..1024\n");
        return 2;
    }
    if (!strcmp(argv[1], "send") && argc >= 3)
        return once ? cmd_send_once(argv[2], seq & 0xFFFF, tx_gain, lo, whiten, lead)
                    : cmd_send(argv[2], seq & 0xFFFF, tx_gain, lo, whiten);
    if (!strcmp(argv[1], "stop"))
        return cmd_stop();
    if (!strcmp(argv[1], "receive"))
        return cmd_receive(count, attempts, rx_gain, lo, whiten, quiet, listen, timeout);
    fprintf(stderr, "unknown command %s\n", argv[1]);
    return 2;
}
