/*
 * zmsg - Lab 11.46 stage 4 from the board consoles: send a text message from board A, receive it on
 * board B, with no Python on either board.
 *
 *   board A$ ./zmsg send "Hello from board A" --seq 17
 *   board B$ ./zmsg receive
 *   board A$ ./zmsg stop
 *
 * send (board A, vendor image with the DAC driver):
 *   packet-v1 (32 bytes: length, sequence LE, up to 27 payload bytes, CRC-16/CCITT-FALSE LE over
 *   bytes 0..29) -> PN9 whitening of the 256 bits -> Lab 11.45 frame (48-bit course preamble +
 *   256 bits) -> differential encoding over the whole cyclic buffer (28 frames, so the buffer wrap
 *   is seamless too) -> QPSK -> RRC (the PL transmitter's own Q15 taps) -> int16 IQ at 0.7 full
 *   scale -> cyclic iio_writedev on cf-ad9361-dds-core-lpc.
 *
 * receive (board B, course image, fabric QPSK modem behind the gpreg bridge at 0x79040000):
 *   Lab 11.45 mode bursts; when a frame locks, the 256 payload bits are read from the bridge's
 *   decoded-bit register (gp_ctrl[16]): payload bit i (48..303) sits at register bit
 *   2*(151 - i/2) + i%2. De-whiten, check the CRC, print the message.
 *
 * The same steps in Python, with the measurements behind them, are in
 * blocks/block_11_integrated_sdr_project/python/two_board_message.py.
 *
 * Build: arm-linux-gnueabihf-gcc -O2 -static -o zmsg zmsg.c -lm
 */
